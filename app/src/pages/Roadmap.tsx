import { useEffect, useState } from 'react'

interface Task { state: 'done' | 'doing' | 'todo'; text: string; feedback?: boolean }
interface Phase { title: string; percent: number; done: number; total: number; tasks: Task[] }
interface Strand { id: string; name: string; nodes: number; withLesson: number; withItems: number }
interface RoadmapData {
  updated: string; overall: number; tasksDone: number; tasksTotal: number
  building: { phase: string; text: string }[]; next: { phase: string; text: string }[]; waiting?: { phase: string; text: string }[]; feedback?: { phase: string; text: string; state: string }[]; phases: Phase[]
  metrics: { skills: number; lessons: number; nodesWithLesson: number; nodesWithItems: number; itemsShipped: number; itemsWaiting: number; itemsNeedHuman: number; itemsHumanReviewed: number; openings: { games?: number; month?: string }; strands: Strand[] }
}

export interface ReadinessArea { id: string; name: string; state: 'not started' | 'in progress' | 'ready for a first audience'; evidence: string[]; conditions: { label: string; met: boolean }[]; next: string | null }
export interface Readiness { updated?: string; areas: ReadinessArea[]; summary: { ready: number; total: number }; rely: string[]; experimental: string[]; afterRelease?: string[]; core?: { percent: number; parts: { label: string; percent: number; detail: string }[]; note: string } }

const bar = (pct: number, label: string) => (
  <div className="rbar" role="progressbar" aria-valuenow={pct} aria-valuemin={0} aria-valuemax={100} aria-label={label}><span style={{ width: `${pct}%` }} /></div>
)
const MARK = { done: '✔', doing: '◐', todo: '○' } as const
const WORD = { done: 'done', doing: 'in progress', todo: 'not started' } as const

export function Roadmap() {
  const [d, setD] = useState<RoadmapData | null>(null)
  const [err, setErr] = useState<string | null>(null)
  const [rd, setRd] = useState<Readiness | null>(null)
  useEffect(() => { fetch(`${import.meta.env.BASE_URL}readiness.json`, { cache: 'no-store' }).then(r => r.ok ? r.json() : Promise.reject(new Error(String(r.status)))).then(setRd).catch(() => setRd(null)) }, [])
  useEffect(() => { fetch(`${import.meta.env.BASE_URL}roadmap.json`, { cache: 'no-store' }).then(r => r.ok ? r.json() : Promise.reject(new Error(String(r.status)))).then(setD).catch(e => setErr(String(e.message ?? e))) }, [])
  if (err) return <main className="page"><h1>Roadmap</h1><p className="warn">The roadmap data is not available ({err}). It is generated by tools/update_roadmap.py.</p></main>
  if (!d) return <main className="page"><h1>Roadmap</h1><p className="muted">Loading…</p></main>
  const m = d.metrics
  const pct = (a: number, b: number) => Math.round((100 * a) / Math.max(1, b))
  return (
    <main className="page wide">
      <h1>Roadmap</h1>
      <p className="lede">What is built, what is being built, and what comes next. Updated {new Date(d.updated).toLocaleString()}. The same list lives in ROADMAP.md.</p>
      {rd?.core && (
        <section className="card">
          <h2>How far is the complete core? About {rd.core.percent}%</h2>
          {bar(rd.core.percent, 'Complete core')}
          <ul className="plain">{rd.core.parts.map(p => <li key={p.label}><strong>{p.percent}%</strong> {p.label} <span className="muted small">· {p.detail}</span></li>)}</ul>
          <p className="small muted">{rd.core.note} Feedback from real people arrives after release and is not part of this number.</p>
        </section>
      )}
      <section className="card">
        <h2>Can people use it yet?</h2>
        {!rd ? <p className="muted small">The readiness view is not available (it is generated by tools/update_roadmap.py).</p> : (
          <>
            <p><strong>{rd.summary.ready} of {rd.summary.total} areas are ready for a first audience.</strong> <span className="small muted">Each area is ready only when every condition listed for it is met; nothing here is a guess.</span></p>
            <table className="table small readiness">
              <thead><tr><th>Area</th><th>State</th><th>Evidence</th><th>Next unresolved condition</th></tr></thead>
              <tbody>{rd.areas.map(a => (
                <tr key={a.id}><td><strong>{a.name}</strong></td><td>{a.state}</td><td><ul className="plain">{a.evidence.map(e => <li key={e}>{e}</li>)}</ul></td><td>{a.next ?? 'None'}</td></tr>))}</tbody>
            </table>
            <div className="grid2">
              <div><h3>What you can rely on today</h3>{rd.rely.length === 0 ? <p className="muted">Nothing yet.</p> : <ul className="plain">{rd.rely.map(x => <li key={x}>{x}</li>)}</ul>}</div>
              <div><h3>What is experimental</h3>{rd.experimental.length === 0 ? <p className="muted">Nothing.</p> : <ul className="plain">{rd.experimental.map(x => <li key={x}>{x}</li>)}</ul>}</div>
            </div>
          </>
        )}
      </section>
      <div className="grid2">
        <section className="card">
          <h2>Building now</h2>
          {d.building.length === 0 ? <p className="muted">Nothing marked in progress.</p> : <ul className="plain">{d.building.map(b => <li key={b.text}><strong>{b.text}</strong> <span className="muted small">· {b.phase.replace(/^Phase \d+: /, '')}</span></li>)}</ul>}
        </section>
        <section className="card">
          <h2>Next up</h2>
          {d.next.length === 0 ? <p className="muted">Nothing left on the list.</p> : <ol className="plain">{d.next.slice(0, 6).map(b => <li key={b.text}>{b.text} <span className="muted small">· {b.phase.replace(/^Phase \d+: /, '')}</span></li>)}</ol>}
        </section>
      </div>
      {(d.waiting?.length ?? 0) > 0 && (
        <section className="card">
          <h2>Waiting on you</h2>
          <p className="small muted">Gates and questions only you can open. Nothing else is blocked on them; details in QUESTIONS-AND-GATES.md.</p>
          <ul className="plain">{d.waiting!.map(b => <li key={b.text}>{b.text} <span className="muted small">· {b.phase.replace(/^Phase \d+: /, '')}</span></li>)}</ul>
        </section>
      )}
      {((d.feedback?.length ?? 0) > 0 || (rd?.afterRelease?.length ?? 0) > 0) && (
        <section className="card">
          <h2>After release: feedback and review</h2>
          <p className="small muted">These wait on real people and arrive over time. None of them blocks a release or counts in a percentage.</p>
          <ul className="plain">{(rd?.afterRelease ?? []).map(x => <li key={x}>{x}</li>)}{(d.feedback ?? []).map(b => <li key={b.text}>{b.state === 'done' ? '✔ ' : '○ '}{b.text}</li>)}</ul>
        </section>
      )}
      <section className="card">
        <h2>The course, measured from the files</h2>
        <p className="small muted">Status of review: positions and results are checked by software; the written explanations have not yet been reviewed by a strong player.</p>
        <p>{m.nodesWithLesson} of {m.skills} skill nodes have a lesson ({pct(m.nodesWithLesson, m.skills)}%), {m.nodesWithItems} have 10 or more exercises ({pct(m.nodesWithItems, m.skills)}%). {m.itemsShipped.toLocaleString()} machine-checked exercises ship; {m.itemsWaiting} more wait for validation. {m.lessons} lessons. {m.itemsHumanReviewed} items have been reviewed by a person so far; {m.itemsNeedHuman.toLocaleString()} are flagged for that review.
          {m.openings.games ? ` Opening statistics: ${m.openings.games.toLocaleString()} online games (${m.openings.month}).` : ''}</p>
        <div style={{ overflowX: 'auto' }}>
        <table className="table small">
          <thead><tr><th>Strand</th><th>Nodes</th><th>With a lesson</th><th>With 10+ exercises</th></tr></thead>
          <tbody>{m.strands.map(s => (
            <tr key={s.id}><td>{s.id} {s.name}</td><td>{s.nodes}</td>
              <td>{s.withLesson}/{s.nodes} {bar(pct(s.withLesson, s.nodes), `${s.name}: lessons`)}</td>
              <td>{s.withItems}/{s.nodes} {bar(pct(s.withItems, s.nodes), `${s.name}: exercises`)}</td></tr>))}</tbody>
        </table>
        </div>
      </section>
      <details className="card">
        <summary><strong>Detailed checklist</strong> <span className="muted small">· {d.tasksDone} of {d.tasksTotal} tasks done; this counts tasks, not effort, and does not say what you can rely on</span></summary>
      {d.phases.map(p => (
        <details key={p.title} className="card">
          <summary><strong>{p.title}</strong> <span className="muted small">· {p.done}/{p.total} · {p.percent}%</span></summary>
          {bar(p.percent, p.title)}
          <ul className="plain">{p.tasks.map(t => <li key={t.text}><span aria-label={WORD[t.state]} title={WORD[t.state]}>{MARK[t.state]}</span> {t.text}</li>)}</ul>
        </details>
      ))}
      </details>
    </main>
  )
}
